CREATE TABLE IF NOT EXISTS products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
 sku VARCHAR(48) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL,
 category VARCHAR(32) NOT NULL, material VARCHAR(32) NOT NULL,
 price DECIMAL(12,2) NOT NULL CHECK (price > 0),
 weight_min DECIMAL(9,3) NOT NULL, weight_max DECIMAL(9,3) NOT NULL,
 labor_fee DECIMAL(10,2) NOT NULL, stock INT NOT NULL CHECK (stock >= 0),
 image_url VARCHAR(240) NOT NULL, image_crop VARCHAR(32) NOT NULL,
 description VARCHAR(2000) NOT NULL, featured BOOLEAN NOT NULL,
 fresh BOOLEAN NOT NULL, active BOOLEAN NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS gold_prices (
 material VARCHAR(32) PRIMARY KEY, price DECIMAL(12,2) NOT NULL,
 source VARCHAR(100) NOT NULL, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS store_settings (
 id INT PRIMARY KEY CHECK (id = 1), name VARCHAR(60) NOT NULL,
 tagline VARCHAR(160) NOT NULL, phone VARCHAR(30) NOT NULL,
 wechat VARCHAR(80) NOT NULL, notice VARCHAR(300) NOT NULL
);
CREATE TABLE IF NOT EXISTS shop_orders (
 id VARCHAR(40) PRIMARY KEY, guest_hash VARCHAR(64) NOT NULL,
 customer_name VARCHAR(40) NOT NULL, phone VARCHAR(30) NOT NULL,
 address VARCHAR(300) NOT NULL, note VARCHAR(500) NOT NULL,
 status VARCHAR(20) NOT NULL, total DECIMAL(14,2) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_orders_guest ON shop_orders(guest_hash);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id VARCHAR(40) NOT NULL REFERENCES shop_orders(id),
 product_id BIGINT NOT NULL REFERENCES products(id),
 name VARCHAR(120) NOT NULL, sku VARCHAR(48) NOT NULL,
 price DECIMAL(12,2) NOT NULL, quantity INT NOT NULL,
 image_url VARCHAR(240) NOT NULL, image_crop VARCHAR(32) NOT NULL
);
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 action VARCHAR(80) NOT NULL, detail VARCHAR(500) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
